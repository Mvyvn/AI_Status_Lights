/********************************** (C) COPYRIGHT *******************************
 * File Name          : ws2812.h
 * Description        : WS2812B (NeoPixel) driver for CH32V003.
 *
 *  Hardware
 *  --------
 *  Data line  : PD3  (TIM2_CH2 alternate function, push-pull)
 *  LEDs       : 7 x WS2812B connected in series on the same data line
 *
 *  Implementation
 *  --------------
 *  A bit-accurate 800 kHz waveform is produced by TIM2_CH2 in PWM mode 1.
 *  TIM2 runs at 48 MHz with ARR = 59, so one PWM period is exactly
 *      60 / 48 MHz = 1.25 us
 *  which is the WS2812B bit cell.  The high level time of the cell encodes
 *  the bit value:
 *      '0' -> CCR = 19  -> 0.40 us high, 0.85 us low
 *      '1' -> CCR = 38  -> 0.80 us high, 0.45 us low
 *  The CCR register is written by DMA1_Channel2 (the CH32V003 DMA request
 *  line of the TIM2 update event) directly from a pre-computed buffer, so
 *  the timing is generated by hardware and is not disturbed by interrupts
 *  or by the CPU executing other code.
 *******************************************************************************/
#ifndef __WS2812_H
#define __WS2812_H

#include "ch32v00x.h"

/* Number of WS2812B LEDs chained on the data line. */
#define WS2812_LED_NUM              7

/* Data output pin. */
#define WS2812_GPIO_PORT            GPIOD
#define WS2812_GPIO_PIN             GPIO_Pin_3

/* Colour order used by the WS2812B protocol: G7..G0, R7..R0, B7..B0. */
#define WS2812_ORDER_GRB            1

/* Initialise the GPIO / timer / DMA hardware.  Must be called once before
 * any other WS2812 function, after SystemCoreClockUpdate(). */
void WS2812_Init(void);

/* Store a colour into the software frame buffer (no output is generated).
 * index : 0 .. WS2812_LED_NUM-1, counted from the LED closest to the MCU.
 * r/g/b : 0 .. 255 per channel. */
void WS2812_SetPixel(uint8_t index, uint8_t r, uint8_t g, uint8_t b);

/* Store the same colour into every LED of the frame buffer. */
void WS2812_SetAll(uint8_t r, uint8_t g, uint8_t b);

/* Set the whole frame buffer to black (all LEDs off). */
void WS2812_Clear(void);

/* Compute the DMA bit-stream from the frame buffer and shift it out to the
 * LEDs.  The necessary >50 us reset/low time is generated before the frame
 * starts.
 * returns WS2812_OK when the frame was shifted out, or WS2812_ERR_TIMEOUT
 * when the DMA transfer never completed (the line is parked low in that
 * case, so nothing is damaged). */
#define WS2812_OK                   0
#define WS2812_ERR_TIMEOUT          1
uint8_t WS2812_Refresh(void);

#endif /* __WS2812_H */
